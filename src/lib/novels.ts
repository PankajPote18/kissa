const escapeXml = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const wrapTitle = (title: string, maxCharsPerLine = 15): string[] => {
  const words = title.split(" ");
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (next.length > maxCharsPerLine && current) {
      lines.push(current);
      current = word;
    } else {
      current = next;
    }
  }
  if (current) lines.push(current);
  return lines;
};

function placeholderCover(title: string, index: number): string {
  const [from, to] = coverPalette[index % coverPalette.length]!;
  const lines = wrapTitle(title);
  const lineHeight = 46;
  const startY = 480 - ((lines.length - 1) * lineHeight) / 2;
  const tspans = lines
    .map((line, i) => `<tspan x="320" y="${startY + i * lineHeight}">${escapeXml(line)}</tspan>`)
    .join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="640" height="960" viewBox="0 0 640 960">
    <defs>
      <linearGradient id="g${index}" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0" stop-color="${from}"/>
        <stop offset="1" stop-color="${to}"/>
      </linearGradient>
    </defs>
    <rect width="640" height="960" fill="url(#g${index})"/>
    <rect width="640" height="960" fill="black" opacity="0.18"/>
    <text font-family="Georgia, serif" font-size="42" font-weight="700" fill="white" text-anchor="middle" dominant-baseline="middle">${tspans}</text>
  </svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

